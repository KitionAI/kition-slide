import {
  AnimationAppearIcon,
  AnimationFadeIcon,
  AnimationFadeOutIcon,
  AnimationFloatInIcon,
  AnimationFlyInIcon,
  AnimationFlyOutIcon,
  AnimationGrowShrinkIcon,
  AnimationPathIcon,
  AnimationPulseIcon,
  AnimationSpinIcon,
  AnimationSplitIcon,
  AnimationWipeIcon,
  AnimationZoomIcon,
  SparkleIcon,
  SparklesIcon,
  TransitionCoverIcon,
  TransitionCurtainsIcon,
  TransitionCutIcon,
  TransitionDrapeIcon,
  TransitionFadeIcon,
  TransitionFallOverIcon,
  TransitionFlashIcon,
  TransitionMorphIcon,
  TransitionNoneIcon,
  TransitionPrestigeIcon,
  TransitionPushIcon,
  TransitionRandomBarsIcon,
  TransitionRevealIcon,
  TransitionShapeIcon,
  TransitionSplitIcon,
  TransitionUncoverIcon,
  TransitionWindIcon,
  TransitionWipeIcon,
  type IconComponent,
} from '@kition/tessera/icons/react'

/** Each animation effect's own Tessera icon (engine effect ids); others draw the generic sparkles. */
const ANIMATIONS: Readonly<Record<string, IconComponent>> = {
  appear: AnimationAppearIcon,
  fade: AnimationFadeIcon,
  fly: AnimationFlyInIcon,
  float: AnimationFloatInIcon,
  split: AnimationSplitIcon,
  wipe: AnimationWipeIcon,
  zoom: AnimationZoomIcon,
  pulse: AnimationPulseIcon,
  spin: AnimationSpinIcon,
  growShrink: AnimationGrowShrinkIcon,
  fadeOut: AnimationFadeOutIcon,
  flyOut: AnimationFlyOutIcon,
  lines: AnimationPathIcon,
}

/** Each transition's own Tessera icon (engine transition kinds); others draw the generic sparkle. */
const TRANSITIONS: Readonly<Record<string, IconComponent>> = {
  none: TransitionNoneIcon,
  morph: TransitionMorphIcon,
  fade: TransitionFadeIcon,
  push: TransitionPushIcon,
  wipe: TransitionWipeIcon,
  split: TransitionSplitIcon,
  reveal: TransitionRevealIcon,
  cut: TransitionCutIcon,
  randomBar: TransitionRandomBarsIcon,
  shape: TransitionShapeIcon,
  uncover: TransitionUncoverIcon,
  cover: TransitionCoverIcon,
  flash: TransitionFlashIcon,
  fallOver: TransitionFallOverIcon,
  drape: TransitionDrapeIcon,
  curtains: TransitionCurtainsIcon,
  wind: TransitionWindIcon,
  prestige: TransitionPrestigeIcon,
}

export const animationIcon = (effect: string): IconComponent => ANIMATIONS[effect] ?? SparklesIcon
export const transitionIcon = (kind: string): IconComponent => TRANSITIONS[kind] ?? SparkleIcon
